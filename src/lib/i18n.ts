const catalogs: Record<AppLanguage, Record<MessageKey, string>> = { de, en };

export function translate(
  lang: AppLanguage,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  let text = catalogs[lang][key] ?? catalogs.de[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

export function localeTag(lang: AppLanguage): string {
  return lang === "en" ? "en-US" : "de-DE";
}
